"""Render accepted findings as a bug bounty report (Markdown).

Reproduction steps are built from the captured requests, not generated, so they are
always accurate. Credentials are redacted.
"""
from __future__ import annotations

import re
from datetime import date

from .models import Finding, HttpExchange, Status
from .rag import Retriever
from .triage import redact

STEP_HINTS = {
    "idor": "Repeat the request with your own second test account's session and confirm the other account's data is returned.",
    "missing_authorization": "Repeat the request with no Cookie or Authorization header and confirm the data is still returned.",
    "reflected_input": "Open the URL in a browser and confirm whether the reflected value is interpreted as markup.",
    "verbose_error": "Observe the internal error detail in the response body.",
    "sensitive_data_exposure": "Observe the sensitive fields in the response body.",
    "cors_misconfiguration": "Repeat the request with an untrusted Origin header and confirm it is reflected with credentials allowed.",
}


def _fence(text: str, lang: str = "") -> str:
    """Code block that captured traffic cannot break out of, whatever backticks it contains."""
    ticks = "`" * max(3, max((len(r) for r in re.findall(r"`+", text)), default=0) + 1)
    return f"{ticks}{lang}\n{text}\n{ticks}"


def _code(text: str) -> str:
    """Inline code span, safe for text containing backticks or newlines."""
    text = " ".join(text.split())
    ticks = "`" * (max((len(r) for r in re.findall(r"`+", text)), default=0) + 1)
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{ticks}{pad}{text}{pad}{ticks}"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _request_block(ex: HttpExchange) -> str:
    return _fence(redact(ex.request_text())[:2000], "http")


def finding_markdown(f: Finding, by_id: dict[int, HttpExchange], retriever: Retriever) -> str:
    exs = [by_id[i] for i in f.exchange_ids if i in by_id]
    lines = [
        f"## {' '.join(f.title.split())}",
        "",
        f"**Severity:** {f.severity.value.capitalize()}  ",
        f"**Class:** {f.vuln_class.value.replace('_', ' ')}  ",
        f"**Endpoint:** {_code(f.endpoint)}  ",
        f"**Confidence (tool):** {f.confidence:.0%}",
        "",
        "### Summary",
        f.rationale,
        "",
        "### Steps to reproduce",
        "1. Log in with the test account used during testing (if the request below carries a session).",
    ]
    n = 2
    for ex in exs[:2]:
        lines += [f"{n}. Send the following request:", "", _request_block(ex), "",
                  f"   The server responded with **HTTP {ex.status}**."]
        n += 1
    lines.append(f"{n}. {STEP_HINTS.get(f.vuln_class.value, 'Observe the response.')}")
    lines += ["", "### Evidence", *[f"- {_code(redact(e)[:200])}" for e in f.evidence], ""]
    lines += ["### Remediation", f.remediation, ""]
    if f.references:
        titles = [retriever.get(r).title if retriever.get(r) else r for r in f.references]
        lines += ["### References", *[f"- {t}" for t in titles], ""]
    if f.tester_notes:
        lines += ["### Tester notes", f.tester_notes, ""]
    return "\n".join(lines)


def build_report(project: dict, retriever: Retriever, include_pending: bool = False) -> str:
    by_id = {e.id: e for e in project["exchanges"]}
    wanted = {Status.ACCEPTED} | ({Status.PENDING} if include_pending else set())
    findings = [f for f in project["findings"] if f.status in wanted]
    head = [
        f"# Security findings: {project['name']}",
        "",
        f"Generated by Burp-to-Report on {date.today().isoformat()}. "
        f"{len(findings)} finding(s) confirmed by the tester. Session tokens are redacted.",
        "",
        "| # | Severity | Title |",
        "|---|----------|-------|",
        *[f"| {i} | {f.severity.value.capitalize()} | {_cell(f.title)} |" for i, f in enumerate(findings, 1)],
        "",
        "---",
        "",
    ]
    body = "\n\n---\n\n".join(finding_markdown(f, by_id, retriever) for f in findings)
    return "\n".join(head) + body + "\n"
